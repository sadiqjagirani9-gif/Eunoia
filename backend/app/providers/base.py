from typing import Protocol


class ProviderAdapter(Protocol):
    def endpoint(self, config: dict) -> str: ...
    def headers(self, config: dict) -> dict[str, str]: ...
    def payload(self, config: dict, messages: list[dict], stream: bool) -> dict: ...
    def parse_event(self, line: str) -> tuple[str, int | None, int | None]: ...
